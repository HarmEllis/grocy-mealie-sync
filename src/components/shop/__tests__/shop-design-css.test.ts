import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';
import { describe, expect, it } from 'vitest';
import { buildCss } from '../../../../scripts/port-shop-design-css.mjs';

const css = fs.readFileSync(path.resolve(__dirname, '../shop-design.css'), 'utf8');
const ast = postcss.parse(css);

describe('shop-design.css (generated by scripts/port-shop-design-css.mjs)', () => {
  it('matches what the port script generates (rerun `node scripts/port-shop-design-css.mjs`)', () => {
    expect(css).toBe(buildCss());
  });

  it('keeps every rule in the components layer so Tailwind utilities still win (unlayered CSS beats layers)', () => {
    expect(css).toMatch(/@layer theme, base, components, utilities;/);
    const unlayered: string[] = [];
    ast.walkRules(rule => {
      let parent: postcss.Container | postcss.Document | undefined = rule.parent;
      let layered = false;
      while (parent) { if (parent.type === 'atrule' && (parent as postcss.AtRule).name === 'layer') layered = true; parent = parent.parent; }
      const onlyVariables = rule.nodes.every(node => node.type === 'decl' && node.prop.startsWith('--'));
      if (!layered && !onlyVariables) unlayered.push(rule.selector);
    });
    expect(unlayered).toEqual([]);
  });

  it('does not style checkboxes, radios or SVGs that carry their own size', () => {
    expect(css).not.toMatch(/:where\(\.shop-v2\) input[,{]/);
    expect(css).not.toMatch(/:where\(\.shop-v2\) svg\s*[,{]/);
    // :where() keeps the guards at zero specificity, so class rules such as `.search input` still win.
    expect(css).toContain('svg:where(:not([width]))');
    expect(css).toContain('input:where(:not([type="checkbox"]):not([type="radio"]):not([role="combobox"]))');
  });

  it('scopes every rule under .shop-v2 so it cannot leak into the rest of the app', () => {
    const unscoped: string[] = [];
    ast.walkRules(rule => {
      if (rule.parent?.type === 'atrule' && (rule.parent as postcss.AtRule).name === 'keyframes') return;
      for (const selector of rule.selectors) if (!selector.includes('.shop-v2')) unscoped.push(selector);
    });
    expect(unscoped).toEqual([]);
  });

  it('scopes at zero specificity so same-layer rules do not outrank each other', () => {
    ast.walkRules(rule => {
      for (const selector of rule.selectors) expect(selector).not.toMatch(/(^|[\s,])\.shop-v2\b/);
    });
  });

  it('renames every design custom property to --shop-* and leaves app tokens untouched', () => {
    const declared = new Set<string>();
    ast.walkDecls(decl => { if (decl.prop.startsWith('--')) declared.add(decl.prop); });
    expect([...declared].filter(name => !name.startsWith('--shop-'))).toEqual([]);
    for (const used of css.matchAll(/var\((--[a-z0-9-]+)/g)) {
      if (used[1].startsWith('--shop-')) expect(declared.has(used[1]), `${used[1]} is defined`).toBe(true);
    }
  });

  it('prefixes keyframes so they cannot collide with Tailwind animations', () => {
    const names: string[] = [];
    ast.walkAtRules('keyframes', rule => { names.push(rule.params); });
    expect(names.length).toBeGreaterThan(0);
    expect(names.every(name => name.startsWith('shop-'))).toBe(true);
    expect(css).not.toMatch(/animation:\s*(spin|sheen)\b/);
  });

  it('carries no global resets or font imports', () => {
    expect(css).not.toMatch(/@import/);
    ast.walkRules(rule => {
      for (const selector of rule.selectors) expect(selector.trim()).not.toMatch(/^(\*|html|body|:root)\b/);
    });
  });
});
