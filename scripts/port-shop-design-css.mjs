// Ports the Shopping design CSS (docs/design/shopping/src) into src/components/shop/shop-design.css.
// Every rule is scoped under `.shop-v2` (specificity 0 via :where) and every design custom property is
// renamed to `--shop-*`, so the port cannot leak into or collide with the app's own tokens and Tailwind.
// Usage: node scripts/port-shop-design-css.mjs
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import postcss from 'postcss';

const root = path.resolve(import.meta.dirname, '..');
const src = path.join(root, 'docs/design/shopping/src');
const out = path.join(root, 'src/components/shop/shop-design.css');
const files = ['shared.css', 'shop-workspace.css', 'receipt-mappings.css', 'shopping.css'];

const designVars = new Set([...fs.readFileSync(path.join(src, 'shared.css'), 'utf8').matchAll(/--([a-z0-9-]+)\s*:/g)].map(m => m[1]));
const renameVars = text => text.replace(/--([a-z0-9-]+)/g, (all, name) => (designVars.has(name) ? `--shop-${name}` : all));
const SCOPE = ':where(.shop-v2)';
// Application shell rules from shared.css; the app has its own shell.
const SHELL = /^(\.(sidebar|brand|nav-label|nav-item|sidebar-bottom|local-status|avatar|app-main|topbar|topbar-path|topbar-end|mobile-menu|bottom-tabs?|bottom-tab|appearance|accent-choice|toast|theme-toggle)\b)/;
const GLOBAL = /^(\*|html|body|:root|\[data-theme[^\]]*\]$|\[data-accent[^\]]*\]$|\[data-theme[^\]]*\]\s*,?$)/;

function scopeSelector(selector) {
  const sel = selector.trim();
  if (GLOBAL.test(sel) || SHELL.test(sel)) return null;
  if (sel.startsWith('[data-theme') || sel.startsWith('[data-accent')) {
    const m = sel.match(/^(\[data-(?:theme|accent)[^\]]*\])\s+(.*)$/);
    return m ? `${m[1]} ${SCOPE} ${m[2]}` : null;
  }
  const guarded = sel
    .replace(/^input(?=$|::|:)/, 'input:where(:not([type="checkbox"]):not([type="radio"]):not([role="combobox"]))')
    .replace(/^svg$/, 'svg:where(:not([width]))');
  return `${SCOPE} ${guarded}`;
}

export function buildCss() {
const keyframes = new Set();
const result = [];
for (const file of files) {
  const css = fs.readFileSync(path.join(src, file), 'utf8').replace(/@import\s+url\([^)]*\);?/g, '');
  const ast = postcss.parse(renameVars(css));
  ast.walkAtRules('keyframes', rule => { keyframes.add(rule.params); rule.params = `shop-${rule.params}`; });
  ast.walkRules(rule => {
    if (rule.parent?.type === 'atrule' && rule.parent.name === 'keyframes') return;
    const selectors = rule.selectors.map(scopeSelector).filter(Boolean);
    if (selectors.length === 0) rule.remove(); else rule.selectors = selectors;
  });
  ast.walkAtRules(rule => { if (rule.name !== 'keyframes' && rule.nodes && rule.nodes.length === 0) rule.remove(); });
  result.push(`/* ---- ${file} ---- */\n${ast.toString()}`);
}
let css = result.join('\n\n');
for (const name of keyframes) css = css.replace(new RegExp(`(animation(?:-name)?\\s*:[^;}]*?)\\b${name}\\b`, 'g'), `$1shop-${name}`);

const tokens = `/* Generated by scripts/port-shop-design-css.mjs from docs/design/shopping/src. Do not edit by hand. */
@layer theme, base, components, utilities;
:where(.shop-v2) {
  --shop-bg: var(--bg-0);
  --shop-surface: var(--bg-1);
  --shop-border: var(--border-color);
  --shop-raised: var(--bg-2);
  --shop-hover: var(--bg-3);
  --shop-sidebar-bg: var(--sidebar-bg);
  --shop-topbar-bg: var(--topbar-bg);
  --shop-panel-bg: #10151e;
  --shop-fg: var(--text-1);
  --shop-muted: var(--text-2);
  --shop-faint: var(--text-3);
  --shop-accent: var(--accent);
  --shop-accent-hover: var(--accent-hover);
  --shop-accent-ink: var(--accent-fg);
  --shop-accent-subtle: var(--accent-subtle);
  --shop-accent-glow: var(--accent-glow);
  --shop-accent-badge: var(--badge-accent-bg);
  --shop-success: var(--badge-success-text);
  --shop-success-bg: var(--badge-success-bg);
  --shop-warning: var(--badge-warning-text);
  --shop-warning-bg: var(--badge-warning-bg);
  --shop-danger: var(--badge-error-text);
  --shop-error-bg: var(--badge-error-bg);
  --shop-info: var(--shop-accent);
  --shop-font-display: var(--font-sans), sans-serif;
  --shop-font-body: var(--font-sans), sans-serif;
  --shop-font-mono: var(--font-mono), monospace;
  --shop-space-1: 4px; --shop-space-2: 8px; --shop-space-3: 12px; --shop-space-4: 16px;
  --shop-space-5: 20px; --shop-space-6: 24px; --shop-space-8: 32px;
  --shop-radius: 0.625rem;
  --shop-radius-sm: calc(var(--shop-radius) - 4px);
  --shop-radius-md: var(--shop-radius);
  --shop-radius-lg: calc(var(--shop-radius) + 4px);
}
[data-theme="light"] :where(.shop-v2) { --shop-panel-bg: #fff; }
`;
// Unlayered CSS beats every `@layer` rule regardless of specificity, so the port lives in the
// `components` layer: above Tailwind's base, below its utilities, which therefore keep winning.
return `${tokens}\n@layer components {\n${css}\n}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  fs.writeFileSync(out, buildCss());
  console.log(`wrote ${path.relative(root, out)} (${(fs.statSync(out).size / 1024).toFixed(1)} KB)`);
}
